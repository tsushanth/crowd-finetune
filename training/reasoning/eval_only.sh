#!/usr/bin/env bash
set -euo pipefail
SCDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCDIR/../.." && pwd)"
cd "$REPO"
BASE="Qwen/Qwen2.5-3B-Instruct"
OUT="outputs"
echo "[1/6] GSM8K base"
python -m training.reasoning.eval_judge --model "$BASE" --limit 100 --output "data/eval_base.json"
echo "[2/6] GSM8K SFT"
python -m training.reasoning.eval_judge --model "$OUT/reasoning-sft-merged" --limit 100 --output "data/eval_sft.json"
echo "[3/6] GSM8K GRPO"
python -m training.reasoning.eval_judge --model "$OUT/reasoning-grpo-merged" --limit 100 --output "data/eval_grpo.json"
echo "[4/6] MATH-500 base"
python -m training.reasoning.eval_judge --model "$BASE" --dataset HuggingFaceH4/MATH-500 --limit 100 --output "data/eval_base_math.json"
echo "[5/6] MATH-500 SFT"
python -m training.reasoning.eval_judge --model "$OUT/reasoning-sft-merged" --dataset HuggingFaceH4/MATH-500 --limit 100 --output "data/eval_sft_math.json"
echo "[6/6] MATH-500 GRPO"
python -m training.reasoning.eval_judge --model "$OUT/reasoning-grpo-merged" --dataset HuggingFaceH4/MATH-500 --limit 100 --output "data/eval_grpo_math.json"
echo "EVALS DONE"